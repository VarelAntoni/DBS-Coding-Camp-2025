"""mengubah label f menjadi F"""

Q1 = df[numerical_cols].quantile(0.25)
Q3 = df[numerical_cols].quantile(0.75)
IQR = Q3 - Q1

df = df[~((df[numerical_cols] < (Q1 - 1.5 * IQR)) |(df[numerical_cols] > (Q3 + 1.5 * IQR))).any(axis=1)]

print("Cleaned DataFrame shape:", df.shape)

"""menghandle nilai outlier yang dapat merusak modelling"""

from sklearn.preprocessing import StandardScaler

scaler = StandardScaler()
df[numerical_cols] = scaler.fit_transform(df[numerical_cols])

print(df.head())

"""melakukan scaling kepada numerical features"""

from sklearn.preprocessing import LabelEncoder

label_encoder = LabelEncoder()
df['CLASS'] = label_encoder.fit_transform(df['CLASS'])
print(df[['CLASS', 'CLASS']].head())

